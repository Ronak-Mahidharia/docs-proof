"""Step 2, first half: the commands in the docs, checked against the code, with nothing run.

1. Audit: every documented command in the 30 pinned repositories, as they are, checked for options the code
   doesn't declare (data/results/audit.jsonl). Each finding is checked by hand in data/hand_check.json ("audit").
2. The answer key: for each planted change, the documented commands it made wrong (data/results/commands.jsonl).
The totals and scores are in data/results/commands-scores.json and docs/results/commands.md.

    python scripts/run_commands.py
"""
from __future__ import annotations

import json
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "scripts"))

from build_cases import clone, folder  # noqa: E402
from docsproof.commands import Problem, commands, console_scripts, main_packages, new_problems, problems  # noqa: E402
from docsproof.names import Code  # noqa: E402
from docsproof.plant import apply  # noqa: E402
from run_baseline import RESULTS, load_cases, pct, report  # noqa: E402


def load_rows(name: str) -> dict[str, list[tuple[str, int]]]:
    rows = [json.loads(line) for line in (RESULTS / name).read_text(encoding="utf-8").splitlines()]
    return {r["id"]: [(p["file"], p["line"]) for p in r["predicted"]] for r in rows}


def audit(repos: list[dict]) -> tuple[list[dict], dict[str, list[Problem]]]:
    """(a summary for each repository, its findings) for the repositories as pinned."""
    summary, findings = [], {}
    for entry in repos:
        root = folder(entry["repo"])
        code = Code(root)
        found = commands(root)
        checked = bool(code.options())
        findings[entry["repo"]] = problems(root, code)
        summary.append({"repo": entry["repo"], "split": entry["split"],
                        "programs": sorted(console_scripts(root) | {f"python -m {m}" for m in main_packages(root)}),
                        "commands": len(found), "commands_with_options": sum(1 for c in found if c.options),
                        "checked": checked, "findings": len(findings[entry["repo"]])})
    return summary, findings


def hand_verdicts(findings: dict[str, list[Problem]]) -> dict:
    """The hand check of the audit's findings. Stops if a finding hasn't been checked, or a check names a
    finding that's no longer there."""
    checks = json.loads((ROOT / "data" / "hand_check.json").read_text(encoding="utf-8"))["audit"]["findings"]
    found = {(repo, p.file, p.line, p.option) for repo, rows in findings.items() for p in rows}
    checked = {(c["repo"], c["file"], c["line"], c["option"]) for c in checks}
    if found != checked:
        raise SystemExit(f"Check these audit findings by hand first: {sorted(found - checked)}; "
                         f"no longer found: {sorted(checked - found)}")
    reasons: dict[str, int] = {}
    for c in checks:
        if c["verdict"] == "false alarm":
            reasons[c["reason"]] = reasons.get(c["reason"], 0) + 1
    return {"out_of_date": sum(1 for c in checks if c["verdict"] == "out of date"),
            "false_alarms": sum(reasons.values()), "reasons": dict(sorted(reasons.items(), key=lambda r: -r[1]))}


def markdown(summary: list[dict], hand: dict, scores: dict, exact: dict) -> str:
    unchecked = [r["repo"] for r in summary if r["programs"] and not r["checked"]]
    none = [r["repo"] for r in summary if not r["programs"]]
    reasons = "; ".join(f"{reason} ({n})" for reason, n in hand["reasons"].items())
    lines = ["# Commands in the docs, checked against the code", "",
             "Generated by `scripts/run_commands.py`. Don't edit by hand.", "",
             "A documented command is a command in a code block, or in inline code, that runs one of the project's "
             "own programs: a console script, or `python -m` with one of its packages. It's read the way a shell "
             "reads it, and its long options are compared with the options the code declares. Nothing is run.", "",
             "## Audit: the 30 repositories as pinned", "",
             f"- **{sum(r['commands'] for r in summary):,} documented commands**, "
             f"{sum(r['commands_with_options'] for r in summary)} of them with long options.",
             f"- **Not checked:** {', '.join(unchecked)}, whose command line isn't declared in Python; "
             f"{' and '.join(none)} have no command line.",
             f"- **Findings:** {sum(r['findings'] for r in summary)} options the code doesn't declare. Checked by hand "
             f"([data/hand_check.json](../../data/hand_check.json)): {hand['out_of_date']} out of date, and "
             f"{hand['false_alarms']} false alarms: {reasons}.", "",
             "## The answer key: renamed options", "",
             "A line is flagged when a documented command uses an option the change removed, with proof such as "
             "\"`flask` declares no --host option in the code\". Lines that mention the option outside a command "
             "(in a sentence, a list of options, or help output) are left to the exact checks, which flag every "
             "mention.", "",
             "| Split | Cases | Lines | Flagged | False alarms | Precision | Recall | Exact checks: precision |",
             "|---|---|---|---|---|---|---|---|"]
    for split in ("dev", "test"):
        t, e = scores[split]["kinds"]["rename_option"], exact[split]["kinds"]["rename_option"]
        lines.append(f"| {split} | {t['cases']} | {t['tp'] + t['fn']} | {t['tp'] + t['fp']} | {t['fp']} | "
                     f"{pct(t['precision'])} | {pct(t['recall'])} | {pct(e['precision'])} |")
    flagged = {split: sum(v["tp"] + v["fp"] for k, v in scores[split]["kinds"].items() if k != "rename_option")
               for split in ("dev", "test")}
    lines += ["", f"It flagged {flagged['dev']} lines in dev and {flagged['test']} in test for the other kinds of change, "
              "since it checks options only.", "",
              "## Tried and not used", "",
              "A rule that left out exact-check findings on lines running another program, such as "
              "`waitress-serve --host` in Flask's deployment docs. On dev it removed no false alarms and dropped a "
              "right line: `fuck --yeah`, the command thefuck sets up for itself. Its idea came from a test "
              "repository (Flask), so a test score for it wouldn't be fair.", ""]
    return "\n".join(lines)


def main() -> None:
    repos = json.loads((ROOT / "data" / "repos.json").read_text(encoding="utf-8"))["repos"]
    cases = load_cases()
    summary, findings = audit(repos)
    hand = hand_verdicts(findings)
    with (RESULTS / "audit.jsonl").open("w", encoding="utf-8") as out:
        for repo, rows in findings.items():
            for p in rows:
                out.write(json.dumps({"repo": repo, "file": p.file, "line": p.line, "program": p.program,
                                      "option": p.option, "proof": p.proof}, ensure_ascii=False) + "\n")

    with (RESULTS / "commands.jsonl").open("w", encoding="utf-8") as out:
        for i, case in enumerate(cases, 1):
            original = folder(case["repo"])
            with tempfile.TemporaryDirectory() as tmp:
                copy = Path(tmp) / "repo"
                clone(original, copy)
                apply(copy, case["edit"])
                found = new_problems(original, copy, findings[case["repo"]])
            predicted = [{"file": p.file, "line": p.line, "option": p.option, "proof": p.proof}
                         for p in sorted(found, key=lambda p: (p.file, p.line, p.option))]
            out.write(json.dumps({"id": case["id"], "predicted": predicted}, ensure_ascii=False) + "\n")
            if i % 50 == 0:
                print(f"  {i} of {len(cases)} cases")
    commands_scores = report(cases, load_rows("commands.jsonl"))
    exact = json.loads((RESULTS / "exact-scores.json").read_text(encoding="utf-8"))
    scores = {"audit": {"repos": summary, "commands": sum(r["commands"] for r in summary),
                        "commands_with_options": sum(r["commands_with_options"] for r in summary),
                        "findings": sum(r["findings"] for r in summary), **hand},
              "commands": commands_scores}
    (RESULTS / "commands-scores.json").write_text(json.dumps(scores, indent=1) + "\n", encoding="utf-8")
    (ROOT / "docs" / "results" / "commands.md").write_text(markdown(summary, hand, commands_scores, exact), encoding="utf-8")
    print(f"audit: {scores['audit']['commands']} documented commands, {scores['audit']['findings']} findings, "
          f"{hand['out_of_date']} out of date")
    for split in ("dev", "test"):
        t = commands_scores[split]["kinds"]["rename_option"]
        print(f"{split}: renamed options: flagged {t['tp'] + t['fp']}, false alarms {t['fp']}, "
              f"precision {pct(t['precision'])}, recall {pct(t['recall'])}")

if __name__ == "__main__":
    main()
