"""Step 7: a demo on a real change, docs/demo.md. On Mar 25, 2022, yt-dlp renamed its --match-filter option to
--match-filters (commit b1a7cd05, "Treat multiple `--match-filters` as OR") and left the old name in the README.
This runs the docs-proof command on that commit, the way a maintainer could have that day, and writes its exact
output, with what happened to each line afterwards (data/real_cases.jsonl).

    python scripts/demo.py   # needs the fetched history (scripts/fetch_history.py)
"""
from __future__ import annotations

import contextlib
import io
import json
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "scripts"))

from fetch_history import place  # noqa: E402
from run_baseline import RESULTS  # noqa: E402

CASE = "yt-dlp/yt-dlp@b1a7cd056a"
SHORT = "b1a7cd05"


def run() -> tuple[int, str]:
    """The command's exit status and output, run in a fresh clone at the change."""
    from docsproof import cli
    case = next(json.loads(line) for line in (ROOT / "data" / "real_cases.jsonl").read_text(encoding="utf-8").splitlines()
                if json.loads(line)["id"] == CASE)
    with tempfile.TemporaryDirectory() as tmp:
        clone = Path(tmp) / "yt-dlp"
        subprocess.run(["git", "clone", "-q", "--no-checkout", str(place(case["repo"])), str(clone)], check=True)
        subprocess.run(["git", "-C", str(clone), "checkout", "-q", case["commit"]], check=True)
        out = io.StringIO()
        with contextlib.redirect_stdout(out):
            status = cli.main(["--repo", str(clone), "--base", f"{SHORT}^1", "--head", SHORT])
    return status, out.getvalue()


def afterwards(case: dict | None = None, row: dict | None = None) -> list[str]:
    """What happened to each flagged line: a later fix from the key, or why the key doesn't count it. By default, the
    demo's case from the real-history key and its kept results."""
    case = case or next(json.loads(line) for line in (ROOT / "data" / "real_cases.jsonl").read_text(encoding="utf-8").splitlines()
                        if json.loads(line)["id"] == CASE)
    row = row or next(json.loads(line) for line in (RESULTS / "real.jsonl").read_text(encoding="utf-8").splitlines()
                      if json.loads(line)["id"] == CASE)
    expected = {(e["file"], e["line"]): e for e in case["expected"]}
    out = []
    for x in row["flagged"]:
        e = expected.get((x["file"], x["line"]))
        if e:
            out.append(f"- **{x['file']}:{x['line']}:** fixed on {e['fixed_on']}, {e['days']:,} days later "
                       f"(commit `{e['fixed_by'][:8]}`).")
        elif x.get("still_there"):
            out.append(f"- **{x['file']}:{x['line']}:** still there at the commit the key is pinned to.")
        elif x.get("key_rules_see") and x.get("name_kept"):
            out.append(f"- **{x['file']}:{x['line']}:** changed later (commit `{x['changed_in'][:8]}`), and that commit "
                       "still names the old option in the file, so the real-history key doesn't count it.")
        else:
            out.append(f"- **{x['file']}:{x['line']}:** changed later (commit `{x['changed_in'][:8]}`), in a way the "
                       "real-history key's rules don't read.")
    days = [e["days"] for e in case["expected"]]
    out += ["", f"The lines the key counts stayed wrong for between {min(days):,} and {max(days):,} days."]
    return out


def markdown(status: int, output: str) -> str:
    return "\n".join([
        "# A demo on a real change", "", "Generated by `scripts/demo.py`. Don't edit by hand.", "",
        "On Mar 25, 2022, yt-dlp renamed its `--match-filter` option to `--match-filters` (commit "
        f"[`{SHORT}`](https://github.com/yt-dlp/yt-dlp/commit/{SHORT}), \"Treat multiple `--match-filters` as OR\") and "
        "left the old name in its README. Here is docs-proof run on that commit, the way a maintainer could have run "
        "it that day, with no AI:", "",
        "```console", f"$ git clone https://github.com/yt-dlp/yt-dlp && cd yt-dlp && git checkout {SHORT}",
        f"$ docs-proof --base {SHORT}^1 --head {SHORT}", output.rstrip("\n"), "```", "",
        f"It exits with status {status}, because it flagged doc lines (0 means nothing to fix, and 2 that the check "
        "couldn't run). `--patch FILE` saves the fixes as one patch, and `--apply` shows them and asks before changing "
        "anything.", "",
        "## What happened to these lines", "",
        "The real-history key ([docs/results/real.md](results/real.md)) records when yt-dlp fixed each line:", "",
        *afterwards(), ""])


def main() -> None:
    status, output = run()
    (ROOT / "docs" / "demo.md").write_text(markdown(status, output), encoding="utf-8")
    print(f"wrote docs/demo.md (exit status {status})")


if __name__ == "__main__":
    main()
