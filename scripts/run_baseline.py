"""Run the exact-check baseline on every case in the answer key, and score it.

For each case (data/cases.jsonl): copy the pinned repository, make the planted change, and run the exact
checks (src/docsproof/exact.py), which see only the code before and after, never the case's answer. Every
prediction is saved with its proof (data/results/exact.jsonl), so the scores can be recomputed without the
repositories. Scores are reported for dev and test separately (docs/results/exact.md).

    python scripts/run_baseline.py
"""
from __future__ import annotations

import json
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "scripts"))

from build_cases import clone, folder  # noqa: E402
from docsproof.exact import find  # noqa: E402
from docsproof.plant import apply  # noqa: E402
from docsproof.score import score  # noqa: E402

RESULTS = ROOT / "data" / "results"
KINDS = ["rename_option", "rename_identifier", "rename_env_var", "rename_file", "change_default", "raise_python",
         "rename_private", "rename_unmentioned_option"]
LABELS = {"rename_option": "Renamed option", "rename_identifier": "Renamed function or class",
          "rename_env_var": "Renamed environment variable", "rename_file": "Renamed file",
          "change_default": "Changed default value", "raise_python": "Raised minimum Python version",
          "rename_private": "Renamed private function (nothing to find)",
          "rename_unmentioned_option": "Renamed option no doc mentions (nothing to find)"}


def load_cases() -> list[dict]:
    return [json.loads(line) for line in (ROOT / "data" / "cases.jsonl").read_text(encoding="utf-8").splitlines()]


def load_predictions() -> dict[str, list[tuple[str, int]]]:
    rows = [json.loads(line) for line in (RESULTS / "exact.jsonl").read_text(encoding="utf-8").splitlines()]
    return {r["id"]: [(p["file"], p["line"]) for p in r["predicted"]] for r in rows}


def report(cases: list[dict], predicted: dict[str, list[tuple[str, int]]]) -> dict:
    """Scores by split: each kind, plus the name and value groups and the controls."""
    out = {}
    for split in ("dev", "test"):
        part = [c for c in cases if c["split"] == split]
        totals = score(part, predicted)
        groups = {g: score([c for c in part if c["group"] == g], predicted) for g in ("name", "value", "control")}
        out[split] = {"cases": len(part), "repos": len({c["repo"] for c in part}),
                      "expected_lines": sum(len(c["expected"]) for c in part),
                      "kinds": {k: totals[k] for k in KINDS if k in totals},
                      "name": groups["name"].get("all"), "value": groups["value"].get("all"),
                      "control": {"cases": sum(1 for c in part if c["group"] == "control"),
                                  "false_alarm_cases": sum(1 for c in part if c["group"] == "control"
                                                           and predicted.get(c["id"]))}}
    return out


def pct(x: float | None) -> str:
    return "n/a" if x is None else f"{100 * x:.1f}%"


def markdown(scores: dict) -> str:
    lines = ["# Exact-check baseline", "",
             "Generated by `scripts/run_baseline.py`. Don't edit by hand.", "",
             "The baseline compares the code before and after a planted change, collects the names that "
             "disappeared (long options, functions and classes, environment variables, and file paths), and "
             "flags every doc line that still mentions one. It uses no AI, and it never sees the answer key.", ""]
    for split in ("dev", "test"):
        s = scores[split]
        lines += [f"## {split.capitalize()}: {s['cases']} cases in {s['repos']} repositories, "
                  f"{s['expected_lines']} expected doc lines", "",
                  "| Kind of change | Cases | Precision | Recall | Cases with every line found | Cases with a false alarm |",
                  "|---|---|---|---|---|---|"]
        for kind, t in s["kinds"].items():
            lines.append(f"| {LABELS[kind]} | {t['cases']} | {pct(t['precision'])} | {pct(t['recall'])} | "
                         f"{t['all_found'] if t['tp'] + t['fn'] else 'n/a'} | {t['false_alarm_cases']} |")
        for group, label in (("name", "**The name group** (the docs still say the old name)"),
                             ("value", "**The value group** (no name changes)")):
            t = s[group]
            lines.append(f"| {label} | {t['cases']} | {pct(t['precision'])} | {pct(t['recall'])} | {t['all_found']} | "
                         f"{t['false_alarm_cases']} |")
        c = s["control"]
        lines += ["", f"Controls (nothing to find): {c['false_alarm_cases']} of {c['cases']} cases got a false alarm.", ""]
    return "\n".join(lines)


def main() -> None:
    cases = load_cases()
    cache: dict = {}
    RESULTS.mkdir(parents=True, exist_ok=True)
    with (RESULTS / "exact.jsonl").open("w", encoding="utf-8") as out:
        for i, case in enumerate(cases, 1):
            original = folder(case["repo"])
            with tempfile.TemporaryDirectory() as tmp:
                copy = Path(tmp) / "repo"
                clone(original, copy)
                apply(copy, case["edit"])
                findings = find(original, copy, cache)
            predicted = [{"file": f.file, "line": f.line, "name": f.name, "kind": f.kind, "proof": f.proof}
                         for f in sorted(findings, key=lambda f: (f.file, f.line, f.name))]
            out.write(json.dumps({"id": case["id"], "predicted": predicted}, ensure_ascii=False) + "\n")
            if i % 25 == 0:
                print(f"  {i} of {len(cases)} cases")
    scores = report(cases, load_predictions())
    (RESULTS / "exact-scores.json").write_text(json.dumps(scores, indent=1) + "\n", encoding="utf-8")
    (ROOT / "docs" / "results").mkdir(parents=True, exist_ok=True)
    (ROOT / "docs" / "results" / "exact.md").write_text(markdown(scores), encoding="utf-8")
    for split in ("dev", "test"):
        n, v, c = scores[split]["name"], scores[split]["value"], scores[split]["control"]
        print(f"{split}: name group precision {pct(n['precision'])}, recall {pct(n['recall'])}; "
              f"value group recall {pct(v['recall'])}; controls with a false alarm {c['false_alarm_cases']} of {c['cases']}")


if __name__ == "__main__":
    main()
